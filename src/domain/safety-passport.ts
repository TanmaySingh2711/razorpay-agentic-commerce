/** The only shape this module needs from a timeline entry. */
export interface PassportTimelineEntry {
  readonly action: string;
}

const EMPTY_EVIDENCE: PassportEvidence = {
  productVerified: 0,
  productSelectionRejected: 0,
  quoteCreated: 0,
  quoteReissued: 0,
  policyEvaluated: 0,
  approvalGranted: 0,
  approvalDenied: 0,
  inventoryReserved: 0,
  inventoryRequoted: 0,
  inventoryCommitted: 0,
  paymentVerified: 0,
  paymentCaptured: 0,
  paymentFailed: 0,
  callbackRejected: 0,
  retryRequested: 0,
  webhookDuplicate: 0,
  webhookMismatch: 0,
  multipleCaptureDetected: 0,
  stateTransitions: 0,
  auditedFacts: 0,
};

/** Which audit event type feeds which counter. Anything unlisted is ignored. */
const EVIDENCE_OF: Readonly<Record<string, keyof PassportEvidence>> = {
  product_verified: "productVerified",
  product_selection_rejected: "productSelectionRejected",
  quote_created: "quoteCreated",
  quote_reissued: "quoteReissued",
  policy_evaluated: "policyEvaluated",
  approval_granted: "approvalGranted",
  approval_denied: "approvalDenied",
  inventory_reserved: "inventoryReserved",
  inventory_reservation_requoted: "inventoryRequoted",
  inventory_committed: "inventoryCommitted",
  payment_verified: "paymentVerified",
  payment_captured: "paymentCaptured",
  payment_failed: "paymentFailed",
  payment_callback_rejected: "callbackRejected",
  payment_retry_requested: "retryRequested",
  webhook_duplicate: "webhookDuplicate",
  webhook_mismatch: "webhookMismatch",
  payment_multiple_capture_detected: "multipleCaptureDetected",
};

/**
 * Counts what the trail actually contains.
 *
 * Deliberately tolerant of unknown action names: the audited vocabulary grows
 * with every objective, and a passport that threw on an event type it had not
 * been taught would turn a new audit record into a broken page.
 */
export function countPassportEvidence(
  entries: readonly PassportTimelineEntry[],
): PassportEvidence {
  const counts: Record<keyof PassportEvidence, number> = { ...EMPTY_EVIDENCE };
  for (const entry of entries) {
    if (entry.action === "state_transitioned") {
      counts.stateTransitions += 1;
      continue;
    }
    counts.auditedFacts += 1;
    const key = EVIDENCE_OF[entry.action];
    if (key !== undefined) counts[key] += 1;
  }
  return counts;
}


/**
 * The Agentic Purchase Safety Passport: one panel that answers "why was this
 * AI-assisted purchase safe?" from facts the server already holds.
 *
 * Everything in this file is pure. It takes rows that have already been read -
 * a transaction's state, its quotes, its policy evaluation, its approvals, its
 * stock holds, its payment attempts and its audit trail - and turns them into
 * labelled statuses. It reads no database, calls no provider, and has no clock
 * of its own.
 *
 * ## Why a model is not allowed anywhere near it
 *
 * The passport's entire value is that a reviewer can believe it. A sentence
 * generated by a language model is a plausible sentence, not evidence, and a
 * safety summary that a model wrote would be exactly the artefact this system
 * spends seventeen states avoiding: a confident claim with nothing underneath
 * it. So no branch below takes model output as an input, and there is nowhere
 * for one to be added - the fact type carries persisted values only.
 *
 * ## The rule every branch obeys
 *
 * A positive claim requires evidence for that specific claim. "Captured" is
 * never inferred from a verified callback, "committed" is never inferred from a
 * capture, and "exactly once" is never inferred from a single current row -
 * because a row shows the present, and "once" is a statement about history. The
 * counts taken from the audit trail are what make those distinctions decidable,
 * and where the evidence is absent the honest status is `NOT_REACHED` rather
 * than a blank space that a reader would take for a pass.
 *
 * ## What it is not
 *
 * Not a replacement for the audit timeline. The timeline is the chronological
 * evidence; this is the summary a reviewer reads first. It also makes no
 * absolute claims - nothing here says "secure", "guaranteed" or "fraud-proof",
 * because those are not facts about a transaction. Verified, bounded,
 * authorized, captured, committed and deduplicated are.
 */


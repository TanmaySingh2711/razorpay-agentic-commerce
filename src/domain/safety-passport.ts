/** One payment attempt, as persisted. Nothing here comes from a browser. */
export interface PassportAttemptFact {
  readonly attemptNumber: number;
  /** `PaymentAttemptStatus`, verbatim from the row. */
  readonly status: string;
  readonly amount: MoneyDto;
  readonly failureCategory: PaymentFailureCategory | null;
}

/** One quote, as persisted. */
export interface PassportQuoteFact {
  readonly status: string;
  readonly totalAmount: MoneyDto;
}

/**
 * How many times each audited fact was recorded for this transaction.
 *
 * Counts rather than booleans, because several of the claims below are claims
 * about *how many times* something happened. "Committed exactly once" cannot be
 * decided from a boolean, and deciding it from the single current reservation
 * row would be deciding a question about history from the present tense.
 */
export interface PassportEvidence {
  readonly productVerified: number;
  readonly productSelectionRejected: number;
  readonly quoteCreated: number;
  readonly quoteReissued: number;
  readonly policyEvaluated: number;
  readonly approvalGranted: number;
  readonly approvalDenied: number;
  readonly inventoryReserved: number;
  readonly inventoryRequoted: number;
  readonly inventoryCommitted: number;
  readonly paymentVerified: number;
  readonly paymentCaptured: number;
  readonly paymentFailed: number;
  readonly callbackRejected: number;
  readonly retryRequested: number;
  readonly webhookDuplicate: number;
  readonly webhookMismatch: number;
  readonly multipleCaptureDetected: number;
  /** Lifecycle moves recorded by the state machine. */
  readonly stateTransitions: number;
  /** Audited decisions, excluding lifecycle moves. */
  readonly auditedFacts: number;
}

export interface SafetyPassportFacts {
  readonly transactionId: string;
  readonly state: TransactionState;

  /**
   * The amount this purchase is actually about, taken from a quote row.
   *
   * Null before any quote exists. Never taken from a payment attempt, a request
   * body or a live product row - the quote is the one place a payable amount
   * lives in this system.
   */
  readonly trustedAmount: MoneyDto | null;
  /** The status of the quote that amount came from. */
  readonly trustedQuoteStatus: string | null;
  /** Whether that quote could still be used to start a payment right now. */
  readonly quoteUsable: boolean;
  /** Every quote this transaction has ever had. */
  readonly quotes: readonly PassportQuoteFact[];

  readonly policyDecision: PolicyDecisionKind | null;
  readonly policyReasonCode: string | null;

  /** `ApprovalStatus` values, verbatim. */
  readonly approvalStatuses: readonly string[];
  /** `InventoryReservationStatus` values, verbatim. */
  readonly reservationStatuses: readonly string[];

  readonly attempts: readonly PassportAttemptFact[];
  readonly maxAttempts: number;
  /** Server-computed retry eligibility. Null when no payment path ever opened. */
  readonly retryAvailable: boolean | null;
  readonly retryDenial: string | null;

  readonly evidence: PassportEvidence;
}


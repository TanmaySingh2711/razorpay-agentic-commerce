export const SAFETY_PASSPORT_TITLE = "Agentic Purchase Safety Passport";

/** Builds the passport for one transaction from facts already read. */
export function buildSafetyPassport(facts: SafetyPassportFacts): SafetyPassportViewModel {
  const approval = approvalCheck(facts);
  const stopped = HALTED.has(facts.state) || facts.state === "PAYMENT_FAILED";

  return {
    transactionId: facts.transactionId,
    title: SAFETY_PASSPORT_TITLE,
    // A stopped purchase does not get a success narrative. The passport is an
    // explainability artefact first and a badge second, and a blocked purchase
    // is exactly the case a reviewer most wants explained.
    subtitle: stopped
      ? "What this AI-assisted purchase was allowed to do, and where it stopped."
      : "Why this AI-assisted purchase was allowed to move forward.",
    aiAuthority: {
      label: "AI authority",
      value: "Product proposal only",
      note: "The assistant proposes a product from the merchant's catalog. It cannot set a price, evaluate policy, approve a purchase, hold stock or move money.",
    },
    financialAuthority: {
      label: "Financial authority",
      value: "Deterministic server",
      note: "Every amount, decision and outcome below was produced by server code and read back from persisted rows.",
    },
    priceSource: "Price source: server-verified merchant data.",
    checks: [
      aiBoundedCheck(facts),
      priceCheck(facts),
      policyCheck(facts),
      approval,
      inventoryCheck(facts),
      paymentAmountCheck(facts),
      callbackCheck(facts),
      captureCheck(facts),
      commitCheck(facts),
      transactionCheck(facts),
    ],
    retry: buildRetry(facts),
    properties: buildProperties(facts, approval),
  };
}
